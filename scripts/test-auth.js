import assert from 'node:assert/strict';
import { scrypt as scryptCallback } from 'node:crypto';
import { promisify } from 'node:util';
import { createSession, setSession, sessionEmail } from '../api/_lib/auth.js';
import loginHandler from '../api/login.js';
const scrypt = promisify(scryptCallback);
process.env.SESSION_SECRET = 'test-only-session-secret-with-more-than-32-chars';
process.env.ADMIN_EMAIL = 'admin@example.com';
const token = createSession('admin@example.com');
const headers = {};
setSession({ setHeader: (key, value) => { headers[key] = value; } }, token);
const cookie = headers['Set-Cookie'].split(';')[0];
assert.equal(sessionEmail({ headers: { cookie } }), 'admin@example.com');
assert.equal(sessionEmail({ headers: { cookie: `${cookie}tampered` } }), null);
assert.equal(sessionEmail({ headers: { cookie: 'other=value' } }), null);
const salt = 'a'.repeat(32);
const hash = await scrypt('StrongTestPassword123!', salt, 64);
process.env.ADMIN_PASSWORD_HASH = `scrypt$${salt}$${hash.toString('hex')}`;
const response = { headers: {}, setHeader(k, v) { this.headers[k] = v; }, end(body) { this.body = body; } };
await loginHandler({ method: 'POST', body: { email: 'admin@example.com', password: 'StrongTestPassword123!' }, headers: {} }, response);
assert.equal(response.statusCode, 200);
assert.match(response.headers['Set-Cookie'], /^hz_admin=/);
const failed = { headers: {}, setHeader(k, v) { this.headers[k] = v; }, end(body) { this.body = body; } };
await loginHandler({ method: 'POST', body: { email: 'admin@example.com', password: 'incorrect' }, headers: {} }, failed);
assert.equal(failed.statusCode, 401);
console.log('Authentication and login smoke tests passed.');
